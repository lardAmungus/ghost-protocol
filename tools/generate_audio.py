# -- MOD tracker music ---------------------------------------------------
# 4 channels: ch0=melody, ch1=counter-melody/response, ch2=bass, ch3=drums
# Instruments: 1=melody(sine), 2=bass(triangle), 3=counter(organ),
#              4=kick(noise low), 5=snare(noise high), 6=hihat(noise very high)

def sine32():
    """32-sample looping sine wave, 8-bit signed PCM."""
    return bytes((int(118 * math.sin(2 * math.pi * i / 32)) & 0xFF)
                 for i in range(32))

def triangle32():
    """32-sample looping triangle wave."""
    data = bytearray(32)
    for i in range(32):
        if i < 8:
            data[i] = (i * 16) & 0xFF
        elif i < 24:
            data[i] = (255 - (i - 8) * 16) & 0xFF
        else:
            data[i] = ((i - 24) * 16 - 128) & 0xFF
    return bytes(data)

def organ32():
    """32-sample organ-like wave (fundamental + 2nd + 3rd harmonic)."""
    data = bytearray(32)
    for i in range(32):
        val = int(80 * math.sin(2 * math.pi * i / 32)
                + 35 * math.sin(4 * math.pi * i / 32)
                + 15 * math.sin(6 * math.pi * i / 32))
        data[i] = val & 0xFF
    return bytes(data)

def noise32():
    """32-sample pseudo-noise for percussion."""
    import hashlib
    h = hashlib.sha256(b'ghost_protocol_drums').digest()
    return bytes(h[:32])


def smp_hdr(name, data, vol=56):
    words = len(data) // 2
    return struct.pack('>22sHBBHH',
                       name.encode()[:22].ljust(22, b'\0'),
                       words, 0, vol, 0, words)  # loop_start=0, loop_len=words


def note_cell(note_idx, smp, effect=0, param=0):
    period = PERIODS[note_idx] if 0 <= note_idx < len(PERIODS) else 0
    b1 = ((smp >> 4) << 4) | ((period >> 8) & 0xF)
    b2 = period & 0xFF
    b3 = ((smp & 0xF) << 4) | (effect & 0xF)
    b4 = param & 0xFF
    return bytes([b1, b2, b3, b4])


def build_pattern(cells):
    """cells: [(row, ch, note_idx, smp, effect, param), ...]"""
    pat = bytearray(MOD_ROWS * MOD_CHAN * 4)
    for row, ch, n, smp, fx, param in cells:
        if 0 <= row < MOD_ROWS and 0 <= ch < MOD_CHAN:
            off = (row * MOD_CHAN + ch) * 4
            pat[off:off+4] = note_cell(n, smp, fx, param)
    return bytes(pat)


def build_mod(title, patterns, order, speed=6, bpm=90):
    """Assemble a MOD file with 6 instruments (melody, bass, organ, kick, snare, hihat)."""
    sd_mel   = sine32()
    sd_bass  = triangle32()
    sd_organ = organ32()
    sd_kick  = noise32()
    sd_snare = noise32()
    sd_hihat = noise32()

    title_b = title.encode()[:20].ljust(20, b'\0')
    # Instrument headers: boosted volumes for music prominence
    hdrs  = smp_hdr('Melody',   sd_mel,   64)   # instrument 1
    hdrs += smp_hdr('Bass',     sd_bass,  58)   # instrument 2
    hdrs += smp_hdr('Counter',  sd_organ, 56)   # instrument 3
    hdrs += smp_hdr('Kick',     sd_kick,  52)   # instrument 4
    hdrs += smp_hdr('Snare',    sd_snare, 48)   # instrument 5
    hdrs += smp_hdr('HiHat',    sd_hihat, 40)   # instrument 6
    for _ in range(25):
        hdrs += struct.pack('>22sHBBHH', b'\0'*22, 0, 0, 0, 0, 0)

    # Inject BPM+speed into row 0 of first pattern
    if patterns:
        p0 = bytearray(patterns[0])
        # ch0 row0: BPM
        p0[0]=0x00; p0[1]=0x00; p0[2]=0x0F; p0[3]=bpm & 0xFF
        # ch1 row0: speed
        p0[4]=0x00; p0[5]=0x00; p0[6]=0x0F; p0[7]=speed & 0x1F
        patterns[0] = bytes(p0)

    n_pat = max(order) + 1 if order else 1
    mod   = title_b + hdrs
    mod  += struct.pack('BB', len(order), 0)
    mod  += bytes(order + [0] * (128 - len(order)))
    mod  += b'M.K.'
    for i in range(n_pat):
        mod += patterns[i] if i < len(patterns) else bytes(MOD_ROWS * MOD_CHAN * 4)
    # Sample data
    mod += sd_mel + sd_bass + sd_organ + sd_kick + sd_snare + sd_hihat
    return mod


