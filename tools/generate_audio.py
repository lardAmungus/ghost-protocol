# -- Motif-based melody composition helpers ------------------------------

def motif_repeat(motif, transpose=0, vol_adj=0):
    """Transpose a motif (list of (row_offset, note, vol))."""
    result = []
    for roff, nt, vol in motif:
        new_note = nt + transpose if nt >= 0 else nt
        # Clamp to safe range (0-23, Oct 1-2 only)
        if new_note >= 0:
            new_note = max(0, min(23, new_note))
        result.append((roff, new_note, vol + vol_adj))
    return result

def place_motif(cells, motif, start_row, ch, smp):
    """Place a motif starting at start_row on given channel."""
    for roff, nt, vol in motif:
        row = start_row + roff
        if 0 < row < 64 and nt >= 0:
            cells.append(n(row, ch, nt, smp, max(20, min(64, vol))))


