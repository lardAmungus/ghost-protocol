# -- Scale helpers -------------------------------------------------------

def minor_scale(root):
    """Return note indices for natural minor scale in Oct 1 and Oct 2."""
    intervals = [0, 2, 3, 5, 7, 8, 10]
    notes = []
    for octave_base in [0, 12]:
        for iv in intervals:
            idx = root + octave_base + iv
            if 0 <= idx < 24:
                notes.append(idx)
    return notes

def pentatonic_minor(root):
    """Return pentatonic minor scale notes across Oct 1 and Oct 2."""
    intervals = [0, 3, 5, 7, 10]
    notes = []
    for octave_base in [0, 12]:
        for iv in intervals:
            idx = root + octave_base + iv
            if 0 <= idx < 24:
                notes.append(idx)
    return notes


