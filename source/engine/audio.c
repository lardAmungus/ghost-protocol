static int fade_total = 0;
static int fade_remaining = 0;

void audio_init(void) {
    mmInitDefault((mm_addr)soundbank_bin, 8);
    fade_total = 0;
    fade_remaining = 0;
}

void audio_update(void) { mmFrame(); }

void audio_play_music(int module_id) {
    fade_remaining = 0; fade_total = 0;
    mmSetModuleVolume(1024);
    if (module_id <= MUS_SILENCE || module_id >= MUS_COUNT) { mmStop(); return; }
    mmStart((mm_word)music_map[module_id], MM_PLAY_LOOP);
}

void audio_stop_music(void) { mmStop(); }

void audio_play_sfx(int sfx_id) {
    if (sfx_id <= SFX_NONE || sfx_id >= SFX_COUNT) return;
    mm_sfxhand h = mmEffect((mm_word)sfx_map[sfx_id]); (void)h;
}

void audio_set_intensity(int level) {
    mm_word tempo;
    switch (level) {
    case 2:  tempo = 1200; break;
    case 1:  tempo = 1100; break;
    default: tempo = 1024; break;
    }
    mmSetModuleTempo(tempo);
}

void audio_fade_music(int frames) {
    if (frames <= 0) { mmStop(); return; }
    fade_total = frames; fade_remaining = frames;
}

void audio_update_fade(void) {
    if (fade_remaining <= 0) return;
    fade_remaining--;
    if (fade_remaining <= 0) {
        mmStop(); mmSetModuleVolume(1024); fade_total = 0;
    } else if (fade_total <= 0) {
        mmStop(); mmSetModuleVolume(1024);
        fade_remaining = 0; fade_total = 0;
    } else {
        int vol = (fade_remaining * 1024) / fade_total;
        mmSetModuleVolume((mm_word)vol);
    }
}

